# Test server on your PC: update the claude-work branch, prepare it like the production image (tools/prepare-local.mjs), start the local server and,
# when a Cloudflare tunnel token is available, connect the tunnel (your own domain).
#
#   powershell -ExecutionPolicy Bypass -File scripts\test-server.ps1 [-Branch claude-work] [-NoUpdate] [-NoTunnel]
#
# Tunnel token: the CF_TUNNEL_TOKEN environment variable, or the file .cloudflared-token in the repository root
# (ignored by Git). Without one, or when the cloudflared Windows service already runs, no tunnel is started here.
param(
  [string]$Branch = 'claude-work',
  [switch]$NoUpdate,
  [switch]$NoTunnel
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

function Step($text) { Write-Host "`n== $text" -ForegroundColor Cyan }
function Run($exe, [string[]]$argv) {
  & $exe @argv
  if ($LASTEXITCODE -ne 0) { throw "$exe $($argv -join ' ') failed ($LASTEXITCODE)" }
}

if (-not $NoUpdate) {
  Step "Update $Branch"
  # these files are regenerated by tools/prepare-local.mjs below; any other change is yours and is never discarded
  $generated = @('data', 'content/production/data/local-assets.json', 'content/production/data/local-fx.json',
    'public/i18n/ko/compiled.json', 'shared/languagePacks.js')
  $own = git status --porcelain --untracked-files=no | Where-Object {
    $path = $_.Substring(3); -not ($generated | Where-Object { $path -eq $_ -or $path.StartsWith("$_/") }) }
  if ($own) {
    Write-Host 'Uncommitted changes outside the generated files - commit or stash them first:' -ForegroundColor Yellow
    $own | ForEach-Object { Write-Host "  $_" }
    exit 1
  }
  Run git (@('checkout', '--') + $generated)
  $before = git rev-parse HEAD
  Run git @('fetch', 'origin', $Branch)
  Run git @('checkout', $Branch)
  Run git @('pull', '--ff-only', 'origin', $Branch)
  $after = git rev-parse HEAD
  Write-Host "  $($before.Substring(0,7)) -> $($after.Substring(0,7))"
  $lockChanged = $before -ne $after -and (git diff --name-only $before $after -- package-lock.json)
  if ($lockChanged -or -not (Test-Path 'node_modules')) {
    Step 'npm ci'
    Run npm @('ci')
  }
}

Step 'Prepare the production catalogue, official effects and skins'
Run node @('tools/prepare-local.mjs')

$tunnel = $null
if (-not $NoTunnel) {
  $token = $env:CF_TUNNEL_TOKEN
  if (-not $token -and (Test-Path '.cloudflared-token')) { $token = (Get-Content '.cloudflared-token' -Raw).Trim() }
  $service = Get-Service cloudflared -ErrorAction SilentlyContinue
  if ($service -and $service.Status -eq 'Running') {
    Step 'Tunnel: the cloudflared service is already running'
  } elseif (-not $token) {
    Step 'Tunnel: no token (CF_TUNNEL_TOKEN or .cloudflared-token) - local only'
  } elseif (-not (Get-Command cloudflared -ErrorAction SilentlyContinue)) {
    Step 'Tunnel: cloudflared is not installed (winget install --id Cloudflare.cloudflared) - local only'
  } else {
    Step 'Start the Cloudflare tunnel (its own window)'
    $tunnel = Start-Process cloudflared -ArgumentList @('tunnel', '--no-autoupdate', 'run', '--token', $token) -PassThru
  }
}

Step 'Start the server (Ctrl+C to stop)'
try {
  Run npm @('run', 'dev:local')
} finally {
  if ($tunnel -and -not $tunnel.HasExited) { Stop-Process -Id $tunnel.Id; Write-Host 'Tunnel stopped.' }
}
