import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const result={};
for(const code of ['en','ja','zh']){
 result[code]=[];
 const files=[[`/i18n/${code}/audit.json`,`public/i18n/${code}/audit.json`],[`/i18n/${code}/fork.json`,`public/i18n/${code}/fork.json`],[`/i18n/ko/compiled.json`,`public/i18n/ko/compiled.json`],[`/i18n/${code}.json`,`public/i18n/${code}.json`],[`/i18n/${code}/data.json`,`public/i18n/${code}/data.json`]];
 for(const [path,source]of files.filter(([path])=>code!=='zh'||![`/i18n/${code}.json`,`/i18n/${code}/data.json`].includes(path))){
  const body=await readFile(source);result[code].push({path,bytes:body.length,hash:createHash('sha256').update(body).digest('hex')});
 }
}
// Japanese upstream pack falls back to English for untranslated remake text.
result.ja.push(...result.en.filter(file=>!result.ja.some(own=>own.path===file.path)));
await writeFile('shared/languagePacks.js','// Generated by tools/build-language-packs.mjs; official game text + upstream UI.\nexport const LANGUAGE_PACKS = '+JSON.stringify(result,null,2)+';\n');
