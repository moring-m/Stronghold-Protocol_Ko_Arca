const HOTFIX_VERSION = /^(\d+\.\d+\.\d+[a-z])\d+$/;
const minorOf = (version) => version.match(/^\d+\.\d+\.\d+/)[0];

/** The sections of an update followed by those of its hotfixes (oldest first), each marked with its hotfix version. */
function withHotfixes(note) {
  const hot = (note.hotfixes || []).flatMap((h) => h.sections.map((s) => ({ ...s, hotfix: h.version, hotfixDate: h.date })));
  return { ...note, sections: [...note.sections, ...hot] };
}

/** One A.B.C note: every section title of its updates in order of first use, items oldest first, duplicates dropped. */
function integrated(minor, notes) {
  const sections = new Map();
  for (const note of [...notes].reverse()) {
    for (const s of [...note.sections, ...(note.hotfixes || []).flatMap((h) => h.sections)]) {
      const items = sections.get(s.title) ?? (sections.set(s.title, []), sections.get(s.title));
      for (const item of s.items) if (!items.includes(item)) items.push(item);
    }
  }
  const dates = notes.flatMap((n) => [n.date, ...(n.hotfixes || []).map((h) => h.date)]).sort();
  return {
    version: minor,
    kind: 'integrated',
    date: dates[0] === dates.at(-1) ? dates[0] : `${dates[0]} ~ ${dates.at(-1)}`,
    status: notes.some((n) => n.status === 'released') ? 'released' : 'testing',
    title: '통합 패치노트',
    sections: [...sections].map(([title, items]) => ({ title, items })),
  };
}

function build(releases) {
  const out = [];
  for (let i = 0; i < releases.length;) {
    const minor = minorOf(releases[i].version);
    let j = i;
    while (j < releases.length && minorOf(releases[j].version) === minor) j++;
    const group = releases.slice(i, j);
    out.push(integrated(minor, group), ...group.map(withHotfixes));
    i = j;
  }
  return out;
}

export const PATCH_NOTES = build(RELEASES);

/** The note that describes `version` (a hotfix resolves to its update), or the newest update. */
export function patchNoteFor(version) {
  const v = HOTFIX_VERSION.exec(version)?.[1] ?? version;
  return PATCH_NOTES.find((n) => n.version === v) ?? PATCH_NOTES.find((n) => n.kind !== 'integrated');
}
